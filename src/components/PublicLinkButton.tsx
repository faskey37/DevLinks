export function PublicLinkButton({ link, userId }: Props) {
  async function handleClick() {
    fetch("/api/links/click", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ userId, linkId: link.id }),
    }).catch(() => {});
    window.open(link.url, "_blank", "noopener,noreferrer");
  }

  return (
    <button
      onClick={handleClick}
      className="group flex w-full items-center justify-between rounded-2xl border border-white/5 bg-white/[0.02] px-5 py-4 text-left transition-all hover:-translate-y-0.5 hover:bg-white/[0.05] hover:border-white/10 hover:shadow-lg active:scale-[0.99]"
    >
      <div className="flex items-center gap-3">
        <span className="flex h-9 w-9 flex-shrink-0 items-center justify-center rounded-xl bg-white/5 text-white transition group-hover:scale-110">
          <SocialIcon url={link.url} size={18} />
        </span>
        <span className="font-semibold text-white">{link.title}</span>
      </div>
      <ExternalLink className="h-4 w-4 flex-shrink-0 text-slate-600 transition group-hover:text-slate-400" />
    </button>
  );
}